import numpy as np

# ============================================================
# 1. Dataset
# ============================================================

X = np.array([[0, 0], [0, 1], [1, 0], [1, 1]], dtype=float)

y = np.array([[0], [1], [1], [0]], dtype=float)


# ============================================================
# 2. Activation Functions
# ============================================================


def relu(x):
    return np.maximum(0, x)


def relu_derivative(x):
    return (x > 0).astype(float)


def sigmoid(x):
    return 1 / (1 + np.exp(-x))


# ============================================================
# 3. Loss Function
# ============================================================


def binary_cross_entropy(y, prediction):

    epsilon = 1e-8

    prediction = np.clip(prediction, epsilon, 1 - epsilon)

    loss = -np.mean(y * np.log(prediction) + (1 - y) * np.log(1 - prediction))

    return loss


# ============================================================
# 4. Initialize Parameters
# ============================================================

np.random.seed(42)

# ------------------------------------------------------------
# Layer 1
#
# Input = 2
# Hidden neurons = 4
#
# W1 shape = (2, 4)
# b1 shape = (1, 4)
# ------------------------------------------------------------

W1 = np.random.randn(2, 4) * 0.5

b1 = np.zeros((1, 4))


# ------------------------------------------------------------
# Layer 2
#
# Hidden neurons = 4
# Output neurons = 1
#
# W2 shape = (4, 1)
# b2 shape = (1, 1)
# ------------------------------------------------------------

W2 = np.random.randn(4, 1) * 0.5

b2 = np.zeros((1, 1))


# ============================================================
# 5. Training Configuration
# ============================================================

learning_rate = 0.5

epochs = 10000


# ============================================================
# 6. Training Loop
# ============================================================

for epoch in range(epochs):
    # ========================================================
    # FORWARD PASS
    # ========================================================

    # --------------------------------------------------------
    # Hidden Layer
    #
    # z1 = XW1 + b1
    # --------------------------------------------------------

    z1 = X @ W1 + b1

    # --------------------------------------------------------
    # Apply ReLU
    # --------------------------------------------------------

    a1 = relu(z1)

    # --------------------------------------------------------
    # Output Layer
    #
    # z2 = a1W2 + b2
    # --------------------------------------------------------

    z2 = a1 @ W2 + b2

    # --------------------------------------------------------
    # Apply Sigmoid
    #
    # Converts output into probability
    # --------------------------------------------------------

    a2 = sigmoid(z2)

    # ========================================================
    # CALCULATE LOSS
    # ========================================================

    loss = binary_cross_entropy(y, a2)

    # ========================================================
    # BACKPROPAGATION
    # ========================================================

    # --------------------------------------------------------
    # Output layer gradient
    #
    # For:
    #
    # sigmoid + binary cross entropy
    #
    # dz2 = prediction - actual
    # --------------------------------------------------------

    dz2 = a2 - y

    # --------------------------------------------------------
    # Gradient of W2
    #
    # dW2 = a1.T @ dz2
    # --------------------------------------------------------

    dW2 = a1.T @ dz2

    # --------------------------------------------------------
    # Gradient of b2
    # --------------------------------------------------------

    db2 = np.sum(dz2, axis=0, keepdims=True)

    # --------------------------------------------------------
    # Propagate gradient backwards into hidden layer
    #
    # da1 = dz2 @ W2.T
    # --------------------------------------------------------

    da1 = dz2 @ W2.T

    # --------------------------------------------------------
    # ReLU derivative
    #
    # dz1 = da1 * ReLU'(z1)
    # --------------------------------------------------------

    dz1 = da1 * relu_derivative(z1)

    # --------------------------------------------------------
    # Gradient of W1
    # --------------------------------------------------------

    dW1 = X.T @ dz1

    # --------------------------------------------------------
    # Gradient of b1
    # --------------------------------------------------------

    db1 = np.sum(dz1, axis=0, keepdims=True)

    # ========================================================
    # UPDATE PARAMETERS
    # ========================================================

    W1 -= learning_rate * dW1

    b1 -= learning_rate * db1

    W2 -= learning_rate * dW2

    b2 -= learning_rate * db2

    # ========================================================
    # PRINT LOSS
    # ========================================================

    if epoch % 1000 == 0:
        print(f"Epoch: {epoch}, Loss: {loss:.6f}")


# ============================================================
# 7. FINAL FORWARD PASS
# ============================================================

z1 = X @ W1 + b1

a1 = relu(z1)

z2 = a1 @ W2 + b2

predictions = sigmoid(z2)


# ============================================================
# 8. Print Predictions
# ============================================================

print("\nFinal predictions:")

print(predictions)


# ============================================================
# 9. Convert Probability → Class
# ============================================================

classes = (predictions > 0.5).astype(int)


print("\nPredicted classes:")

print(classes)


# ============================================================
# 10. Actual Answers
# ============================================================

print("\nActual classes:")

print(y.astype(int))


# ============================================================
# 11. Print Learned Parameters
# ============================================================

print("\nLearned parameters:")

print("\nW1:")
print(W1)

print("\nb1:")
print(b1)

print("\nW2:")
print(W2)

print("\nb2:")
print(b2)
